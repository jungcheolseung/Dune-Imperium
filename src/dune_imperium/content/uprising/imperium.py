"""Typed identities and transcribed play data for the Uprising Imperium deck."""

from typing import Any, Final

from dune_imperium.content.core.cards import ImperiumCardEntry, imperium_card_entry
from dune_imperium.content.core.icons import AgentIcon, Faction
from dune_imperium.content.core.schema import GameOption, SourceDocument, SourceRef

BASE_SOURCES: Final = (SourceRef(SourceDocument.MAIN_RULEBOOK, (3, 4)),)
CHOAM_SOURCES: Final = (SourceRef(SourceDocument.MAIN_RULEBOOK, (3, 4, 16)),)
# Promo cards appear in no official document; the card face is the source.
PROMO_SOURCES: Final = (SourceRef(SourceDocument.CARD_FACE, (1,)),)


def _entry(
    catalog_id: int | None,
    slug: str,
    name: str,
    acquisition_cost: int,
    *,
    requires: frozenset[GameOption] = frozenset(),
    **fields: Any,
) -> ImperiumCardEntry:
    return imperium_card_entry(
        catalog_id,
        slug,
        name,
        acquisition_cost,
        catalog_set="uprising",
        sources=(
            PROMO_SOURCES
            if GameOption.PROMO_CARDS in requires
            else CHOAM_SOURCES
            if GameOption.CHOAM_MODULE in requires
            else BASE_SOURCES
        ),
        requires=requires,
        **fields,
    )


