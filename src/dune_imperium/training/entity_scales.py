"""The declared scale of every entity feature column (``entity_features``).

User decision 2026-10-30 ("단위 고정", relayed by the coordinator): a column's
values are divided by a fixed, declared number, not by the largest magnitude
the entities give it, so a new card, Leader or tile never rescales the rows
already there -- it may read past 1 instead (the entity network projects the
features and then applies ``tanh``). The numbers are the scales the
vocabularies had when this table was frozen (claude/base-ix-p4, 2026-10-30),
so every Uprising, original-game and Rise of Ix row read exactly as before,
except one: Rise of Ix's ``agent.sections.rewards:Freighter`` keeps the scale
1 it had before Embedded Agent's two Freighter icons, so Landing Rights reads
1.0 again and Embedded Agent 2.0.

A column a later entity brings that is not listed here falls back to its
computed scale (``entity_features._table``) and fails
``tests/unit/training/test_entity_network.py::
test_every_entity_column_has_a_declared_scale``, which prints the line to add.
"""

